// Writes LICENSES.md from the packages listed in package.json.
// Run with: npm run licenses  (after npm install)
import { readFileSync, writeFileSync } from 'node:fs'

const root = JSON.parse(readFileSync('package.json', 'utf8'))
const section = (title, deps) => {
  const rows = Object.keys(deps ?? {})
    .sort()
    .map((name) => {
      const pkg = JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'))
      const license = typeof pkg.license === 'string' ? pkg.license : 'CHECK MANUALLY'
      return `| ${name} | ${pkg.version} | ${license} |`
    })
  return [`## ${title}`, '', '| Package | Version | License |', '|---|---|---|', ...rows, ''].join(
    '\n',
  )
}

const text = [
  '# Third-party licenses',
  '',
  'Generated by `npm run licenses`. Re-run it whenever a package is added or updated.',
  'Rule: only MIT, ISC, Apache-2.0 and SIL OFL assets. No images or stock photos are bundled.',
  '',
  section('Runtime dependencies (including fonts and icons)', root.dependencies),
  section("Development tools (not shipped to buyers' apps)", root.devDependencies),
].join('\n')

writeFileSync('LICENSES.md', text)
console.log('LICENSES.md written')
